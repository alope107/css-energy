#!/usr/bin/env python3
"""Labels in generated CSS: one format for every project's generator, and an outline of a built page.

  import csslabel as L
  css = [L.header('css-physics/src/gen3d.py', 'css-physics/docs/ARCHITECTURE.md'),
         L.section('Registered properties', 'every engine value: syntax, inheritance, initial value'), ...]
  L.check(text, 'gen3d.py')               # the generator fails if a rule comes before the first section
  python3 shared/py/csslabel.py page.html # the outline: line, level, title (--check: exit 1 if unlabelled);
                                          # a page's linked stylesheets are outlined in its place

The conventions (what gets a label and how it reads) are in shared/README.md#labels-in-generated-css.
"""
import re, sys

_BAD = ('*/', '/*', '{', '}', '<', ']]>', '\n')


def _clean(s, what):
    for b in _BAD:
        if b in s:
            raise ValueError(f'{what} {s!r} contains {b!r}')
    return s


def _label(mark, title, note):
    t = f'/* {mark} {_clean(title, "label")} {mark}'
    return t + (f'\n   {_clean(note, "note")} */' if note else ' */')


def header(generator, doc=None):
    """The stylesheet's first line: what wrote it and where it is explained (paths from the repo root)."""
    _clean(generator, 'generator')
    return (f'/* Generated by {generator}; edit that, not this. '
            + (f'How it works: {_clean(doc, "doc")}. ' if doc else '')
            + 'Outline: python3 shared/py/csslabel.py FILE */')


def section(title, note=None):
    """A subsystem: '/* === Title === */', optionally a one-line note under it."""
    return _label('===', title, note)


def group(title, note=None):
    """A run of rules inside a section: '/* --- Title --- */'."""
    return _label('---', title, note)


_RX = re.compile(r'/\* (===|---) (.*?) \1')


def outline(text):
    """[(line, level, title)] of every label in text (level 1 = section, 2 = group)."""
    out = []
    for n, line in enumerate(text.split('\n'), 1):
        for m in _RX.finditer(line):
            out.append((n, 1 if m.group(1) == '===' else 2, m.group(2)))
    return out


def _styles(text):
    """The stylesheets in text: each <style> element's content, or the whole text if it has none (a .css file)."""
    blocks = re.findall(r'<style[^>]*>(.*?)</style>', text, re.S)
    return blocks if blocks or '<style' in text else [text]


def unlabelled(text):
    """The start of the first rule that comes before any section in one of text's stylesheets, else None."""
    for css in _styles(text):
        css = css.replace('<![CDATA[', '').replace(']]>', '')
        pre = re.split(r'/\* === ', css, maxsplit=1)[0]
        pre = re.sub(r'/\*.*?\*/', '', pre, flags=re.S).strip()
        if pre:
            return pre[:80]
    return None


def check(text, who):
    """Exit if a stylesheet in text has rules before its first section (every generated rule sits under a label);
    returns text, so a generator can wrap what it writes."""
    bad = unlabelled(text)
    if bad is not None:
        raise SystemExit(f'{who}: CSS before the first section label (shared/py/csslabel.py): {bad!r}')
    return text


def linked(path, text):
    """The stylesheets a page links (<link rel="stylesheet" href="…">), as paths relative to the page's."""
    import os
    return [os.path.join(os.path.dirname(path), h) for h in re.findall(r'<link rel="stylesheet" href="([^"]+)"', text)]


if __name__ == '__main__':
    args = []
    for a in sys.argv[1:]:
        if a == '--check':
            continue
        text = open(a, encoding='utf-8', errors='replace').read()
        sheets = linked(a, text)     # a page whose CSS is in linked sheets: outline those, in the page's order
        args += ([a] if not sheets or '<style' in text else []) + sheets
    if not args:
        sys.exit(__doc__)
    rc = 0
    for path in args:
        text = open(path, encoding='utf-8', errors='replace').read()
        if len(args) > 1:
            print(f'{path}:')
        for n, lev, title in outline(text):
            print(f'{n:>7}  {"  " * (lev - 1)}{title}')
        if '--check' in sys.argv and unlabelled(text) is not None:
            print(f'{path}: CSS before the first section label: {unlabelled(text)!r}', file=sys.stderr)
            rc = 1
    sys.exit(rc)
