#!/usr/bin/env python3
"""Assemble spheres pages: one complete engine per sphere count.

  python3 build.py out/spheres.html            # counts 64,128,192,256: out/spheres-N.html per count, linked to each other;
                                               # out/spheres.html is a copy of the DEFAULT count's page
  COUNTS=64 PLAIN=1 python3 build.py one.html  # a single engine with readable names (what the tools expect)
Each engine is generated by gen.py (N = the count) in parallel. Engine knobs (K, RATE, SCENE, ...) pass through.
"""
import json, os, subprocess, sys, tempfile, shutil
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
COUNTS = [int(c) for c in os.environ.get('COUNTS', '64,128,192,256').split(',')]
PLAIN = os.environ.get('PLAIN') == '1'
DEFAULT = int(os.environ.get('DEFAULT', 128 if 128 in COUNTS else COUNTS[0]))
PFX = 'EFHJKMPQ'
tmp = tempfile.mkdtemp()


def build(k):
    n = COUNTS[k]
    env = dict(os.environ, N=str(n))
    if not PLAIN and len(COUNTS) > 1:
        env['PFX'] = PFX[k]
    out = os.path.join(tmp, f'e{n}.json')
    r = subprocess.run([sys.executable, os.path.join(HERE, 'gen.py'), out], env=env, capture_output=True, text=True)
    if r.returncode:
        sys.exit(r.stderr)
    sys.stderr.write(r.stderr.strip().splitlines()[-1] + '\n')
    return json.load(open(out))


with ThreadPoolExecutor(max_workers=os.cpu_count() or 2) as ex:
    engines = list(ex.map(build, range(len(COUNTS))))
e0 = engines[0]
C = e0['consts']
VW, VH = C['VW'], C['VH']
CELL, TC = 10, 20
GC, GR = VW // CELL, VH // CELL
TGC, TGR = 3 * VW // TC, 3 * VH // TC
UI = open(os.path.join(HERE, 'ui.css')).read()
TPL = open(os.path.join(HERE, 'page.html')).read()


def page(sel, dst):
    """the page that shows engine `sel` (an index into COUNTS); the count buttons link to the other pages"""
    e = engines[sel]
    n = COUNTS[sel]
    base = os.path.splitext(os.path.basename(dst))[0]
    stem = base.rsplit('-', 1)[0] if len(COUNTS) > 1 else base
    counts = ''.join(
        (f'<input type="radio" name="n" id="n-{c}" checked><label for="n-{c}">{c}</label>' if c == n else
         f'<a class="cnt" href="{stem}-{c}.html">{c}</a>') for c in COUNTS)
    css = [UI, e['css'], f"#{e['eng_id']}{{display:block}}"]
    rep = {
        '/*UI*/': '\n'.join(css), '/*SHARED*/': '', '/*ENGINES*/': '',
        '<!--ENGINE_HTML-->': e['html'],
        '<!--GRID-->': ('<b>' + '<i></i>' * GR + '</b>') * GC, '<!--TGRID-->': ('<b>' + '<i></i>' * TGR + '</b>') * TGC,
        '<!--COUNTS-->': counts,
        '<!--SCENES-->': ''.join(
            f'<input type="radio" name="sc" id="sc-{sn}"{" checked" if si == 0 else ""}><label id="lb-{sn}" for="sc-{sn}">{sn}</label>'
            for si, sn in enumerate(e['scenes'])),
        '__HVW__': f'{VW / 2:g}', '__HVH__': f'{VH / 2:g}', '__VW__': str(VW), '__VH__': str(VH), '__HS__': str(C['HS']),
        '__PERSP__': C['PERSP'], '__TILT__': C['TILT'], '__TY__': C['TY'], '__NDIST__': str(-float(C['DIST'])).rstrip('0').rstrip('.'),
        '__WX__': str(C['WX']), '__CEIL__': str(C['CEIL']), '__WZ__': str(C['WZ']), '__2WX__': str(2 * C['WX']), '__2WZ__': str(2 * C['WZ']),
        '__2RMAX__': f"{2 * C['RMAX']:g}", '__RMAX__': f"{C['RMAX']:g}", '__GRAV__': e['grav'],
        '__FOOTER__': (f'{n} spheres. Each style pass reads every sphere&rsquo;s position and previous position back from layout '
                       f'through view timelines ({e["nreg"]} registers), predicts, pushes every overlapping pair in a sliding '
                       f'window of {e["K"]} slots apart (the spheres are kept sorted by x, two odd-even sort phases per step), '
                       f'clamps into the tray and writes the next state back into layout: {e["ndecl"]} custom properties on one '
                       f'element, no rule per pair, no JavaScript.'),
    }
    html = TPL
    for k_, v in rep.items():
        html = html.replace(k_, v)
    # the constants the tools need (radii from the type registers)
    html = html.replace('</body>', '<!--SPHERES ' + json.dumps(dict(e['consts'], N=n, K=e['K'])) + '-->\n</body>')
    open(dst, 'w').write(html)


dst = sys.argv[1] if len(sys.argv) > 1 else 'spheres.html'
os.makedirs(os.path.dirname(os.path.abspath(dst)), exist_ok=True)
if len(COUNTS) == 1:
    page(0, dst)
else:
    stem, ext = os.path.splitext(dst)
    for k in range(len(COUNTS)):
        page(k, f'{stem}-{COUNTS[k]}{ext}')
    shutil.copy(f'{stem}-{DEFAULT}{ext}', dst)
shutil.rmtree(tmp)
