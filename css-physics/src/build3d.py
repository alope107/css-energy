#!/usr/bin/env python3
"""Build rigid3d.html: one page per body count, each with its own engine.

  python3 build3d.py rigid3d.html                 # counts 8,16,24,32,48,64: rigid3d-N.html per count, linked to each
                                                  # other; rigid3d.html is a copy of the DEFAULT count's page
  COUNTS=16 PLAIN=1 python3 build3d.py one.html   # one count, readable names, CSS inline (for the test scripts)
  ART=cel python3 build3d.py x.html               # the art style picked on load (art3d.py; default original)
Each engine is generated by gen3d.py (NBOX/NSPH = half the count each) in parallel.

The published pages (not PLAIN, or SHEETS=1) link their CSS as stylesheets named by what they hold (SHEETS below):
the ones every count shares in rigid3d/, which a browser caches once for every count's page, and the count's
engine in rigid3d/N/. PLAIN pages keep it inline in one <style>: the tools read and rewrite the page's CSS.
"""
import json, os, re, shutil, subprocess, sys, tempfile
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', 'shared', 'py'))
import csslabel as lbl     # section and group comments in the output (../../shared/README.md#labels-in-generated-css)
import art3d               # the art styles (style radios, their CSS and SVG filters)
COUNTS = [int(c) for c in os.environ.get('COUNTS', '8,16,24,32,48,64').split(',')]
PLAIN = os.environ.get('PLAIN') == '1'
LINK = os.environ.get('SHEETS', '0' if PLAIN else '1') == '1'
DEFAULT = int(os.environ.get('DEFAULT', 16 if 16 in COUNTS else COUNTS[-1]))
PFX = 'EFHJKMPQ'
tmp = tempfile.mkdtemp()
# the stylesheets, in cascade order: (file, the section it starts at, what writes it). Each is a run of consecutive
# sections; '' files are shared by every count (<stem>/<file>.css), the others are the count's (<stem>/<n>/<file>.css).
# The Gauss–Seidel batches are one sheet per section gen3d.py cut them into (SOLVE_SHEET bytes each), named by levels.
SHEETS = [('', 'page', 'Page layout', 'src/ui3d.css'),
          ('', 'engine', 'Engines: shared wrappers, pointer and controls state', 'src/ui3d.css, src/gen3d.py'),
          ('', 'art', 'Art styles', 'src/art3d.py'),
          ('n', 'properties', 'Registered properties', 'src/gen3d.py'),
          ('n', 'readback', 'Clock and register keyframes', 'src/gen3d.py'),
          ('n', 'predict', 'Predict and broadphase', 'src/gen3d.py'),
          ('n', 'narrowphase', 'Narrowphase', 'src/gen3d.py'),
          ('n', 'solve', 'Gauss–Seidel batches', 'src/gen3d.py'),
          ('n', 'next', 'Next state', 'src/gen3d.py'),
          ('n', 'input', 'Input overrides', 'src/gen3d.py'),
          ('n', 'gates', 'Container names', 'src/gen3d.py'),
          ('n', 'scenes', 'Scene start states', 'src/gen3d.py'),
          ('n', 'registers', 'Registers', 'src/gen3d.py'),
          ('n', 'bodies', 'Bodies', 'src/gen3d.py'),
          ('n', 'touch', 'Touch input (', 'src/gen3d.py')]


def build(k):
    n = COUNTS[k]
    nb = int(os.environ.get('NBOX_FIX', n // 2))
    env = dict(os.environ, NBOX=str(nb), NSPH=str(n - nb))
    if not PLAIN:
        env['PFX'] = PFX[k]
    out = os.path.join(tmp, f'e{n}.json')
    r = subprocess.run([sys.executable, os.path.join(HERE, os.environ.get('GEN', 'gen3d.py')), out], env=env, capture_output=True, text=True)
    if r.returncode:
        sys.exit(r.stderr)
    sys.stderr.write(r.stderr.strip().splitlines()[-1] + '\n')
    return json.load(open(out))


def sheets(css):
    """css cut into SHEETS: [(shared, name, text)]; each solve section is a sheet of its own."""
    secs = [(m.start(), m.group(1)) for m in re.finditer(r'/\* === (.*?) ===', css)]
    cuts = []
    for i, (at, title) in enumerate(secs):
        starts = [s for s in SHEETS if title.startswith(s[2])]
        if starts:
            sh, name, _, gen = starts[0]
            if name == 'solve':
                lo, hi = re.search(r'#\w*?L(\d+)–#\w*?L(\d+)', title).groups()
                name = f'solve-L{lo}-L{hi}'
            cuts.append((at, sh == '', name, gen))
    found = [s[1] for s in SHEETS if any(c[2] == s[1] or c[2].startswith(s[1] + '-L') for c in cuts)]
    assert found == [s[1] for s in SHEETS] and cuts[0][0] == 0, f'sections missing or out of order: {found}'
    assert len({c[2] for c in cuts}) == len(cuts), f'two runs of sections for one sheet: {[c[2] for c in cuts]}'
    out = []
    for (a, shared, name, gen), (b, *_) in zip(cuts, cuts[1:] + [(len(css),)]):
        out.append((shared, name, lbl.header(f'css-physics/{gen}', 'css-physics/docs/ARCHITECTURE.md') + '\n' + css[a:b].strip() + '\n'))
    return out


with ThreadPoolExecutor(max_workers=os.cpu_count() or 2) as ex:
    engines = list(ex.map(build, range(len(COUNTS))))
e0 = engines[0]
C = e0['consts']
VW, VH = C['VW'], C['VH']
# (lighting and the art styles depend only on the faces' normals: the same for every count, so one shared sheet)
assert all(e['shared_css'] == e0['shared_css'] and e['lams'] == e0['lams'] for e in engines)

# pointer grid: columns of cells, 10 view units each (mouse only)
CELL = 10
GC, GR = VW // CELL, VH // CELL
UI = open(os.path.join(HERE, 'ui3d.css')).read()
template = open(os.path.join(HERE, 'page3d.html')).read()
dst = sys.argv[1] if len(sys.argv) > 1 else 'rigid3d.html'
os.makedirs(os.path.dirname(os.path.abspath(dst)), exist_ok=True)
stem = dst[:-5] if dst.endswith('.html') else dst
base = os.path.basename(stem)
outdir = os.path.dirname(stem) or '.'
if LINK:
    shutil.rmtree(os.path.join(outdir, base), ignore_errors=True)   # (sheets of an earlier build's counts)
page_of = {n: f'{base}-{n}.html' if len(COUNTS) > 1 else os.path.basename(dst) for n in COUNTS}
shared_sheets, sizes = None, []
for n, e in zip(COUNTS, engines):
    css = '\n'.join([UI.replace('/*GRID*/', '').replace('/*BODIES*/', ''), e['shared_css'], art3d.css(e['lams'], lbl), e['css']])
    rep = {
        '<!--ARTIN-->': art3d.inputs(os.environ.get('ART', 'original')), '<!--ARTLABELS-->': art3d.labels(), '<!--ARTSVG-->': art3d.svg(),
        '<!--ENGINE_HTML-->': e['html'],
        '<!--GRID-->': ('<b>' + '<i></i>' * GR + '</b>') * GC,
        '<!--COUNTS-->': ''.join(f'<a href="{page_of[m]}"{" class=on" if m == n else ""}>{m}</a>' for m in COUNTS),
        '<!--SCENES-->': ''.join(
            f'<input type="radio" name="sc" id="sc-{sn}"{" checked" if si == 0 else ""}><label id="lb-{sn}" for="sc-{sn}">{sn}</label>'
            for si, sn in enumerate(e['scenes'])),
        '__GC__': str(GC), '__GR__': str(GR),
        '__HVW__': f'{VW / 2:g}', '__HVH__': f'{VH / 2:g}', '__VW__': str(VW), '__VH__': str(VH), '__HS__': str(C['HS']),
        '__PERSP__': C['PERSP'], '__TILT__': C['TILT'], '__TY__': C['TY'], '__NDIST__': str(-float(C['DIST'])).rstrip('0').rstrip('.'),
        '__WX__': str(C['WX']), '__CEIL__': str(C['CEIL']), '__WZ__': str(C['WZ']), '__2WX__': str(2 * C['WX']), '__2WZ__': str(2 * C['WZ']),
        '__GRAV__': e['grav'], '__NMAX__': str(n), '__NREG__': str(e['nreg']),
        '__NPROPS__': f"{e['nprops']:,}", '__NLEV__': str(e['nlev']),
        '__ENGINES_SENTENCE__': f"Each body count ({', '.join(map(str, COUNTS))}) is its own page with its own engine." if len(COUNTS) > 1 else '',
    }
    h = template
    for a, b in rep.items():
        h, css = h.replace(a, b), css.replace(a, b)     # (ui3d.css has placeholders too)
    if LINK:
        cut = sheets(css)
        shared = [(nm, t) for sh, nm, t in cut if sh]
        assert shared_sheets in (None, shared), 'the shared sheets differ between counts'
        shared_sheets = shared
        files = [(f'{base}/{nm}.css' if sh else f'{base}/{n}/{nm}.css', t) for sh, nm, t in cut]
        for path, t in files:
            assert len(t.encode()) < 20 << 20, f'{path} is {len(t.encode()) / 2**20:.1f} MiB: split it (Cloudflare serves at most 25 MiB per file)'
            lbl.check(t, path)
            os.makedirs(os.path.dirname(os.path.join(outdir, path)), exist_ok=True)
            open(os.path.join(outdir, path), 'w').write(t)
        h = h.replace('<!--CSS-->', '\n'.join(f'<link rel="stylesheet" href="{p}">' for p, _ in files))
        sizes.append(f'{n}: {len(cut)} sheets, the engine\'s {sum(len(t) for sh, _, t in cut if not sh) / 1e6:.1f} MB '
                     f'(largest {max(len(t) for _, t in files) / 1e6:.1f} MB)')
    else:
        h = h.replace('<!--CSS-->', '<style>\n' + lbl.check(lbl.header('css-physics/src/build3d.py (page, ui3d.css) and gen3d.py (engine)',
                                                                       'css-physics/docs/ARCHITECTURE.md') + '\n' + css, page_of[n]) + '\n</style>')
        sizes.append(f'{n}: {len(h) / 1e6:.1f} MB')
    if PLAIN and len(COUNTS) == 1:
        h = h.replace('</body>', '<!--BODYINFO ' + json.dumps(e['bodyinfo']) + '-->\n</body>')
    open(os.path.join(outdir, page_of[n]), 'w').write(h)
    if n == DEFAULT and len(COUNTS) > 1:
        open(dst, 'w').write(h)
print(f'{dst}' + (f' + {stem}-N.html' if len(COUNTS) > 1 else '') + (f' + {stem}/' if LINK else '') + ': ' + '; '.join(sizes), file=sys.stderr)
