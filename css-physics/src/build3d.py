#!/usr/bin/env python3
"""Assemble rigid3d.html: one complete engine per body count.

  python3 build3d.py rigid3d.html                 # counts 8,16,24,32,48,64: rigid3d-N.html per count, linked to each
                                                  # other; rigid3d.html is a copy of the DEFAULT count's page
  MULTI=0 python3 build3d.py rigid3d.html         # all counts on one page, picked at runtime with radios
  COUNTS=16 PLAIN=1 python3 build3d.py one.html   # single engine with readable names (for the test scripts)
Each engine is generated by gen3d.py (NBOX/NSPH = half the count each) in parallel.
"""
import json, os, subprocess, sys, tempfile
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
COUNTS = [int(c) for c in os.environ.get('COUNTS', '8,16,24,32,48,64').split(',')]
PLAIN = os.environ.get('PLAIN') == '1'
# several counts: one page per count by default, so a page only parses the engine it shows
MULTI = os.environ.get('MULTI', '1' if len(COUNTS) > 1 else '0') == '1'
DEFAULT_FINE = int(os.environ.get('DEFAULT', 16 if 16 in COUNTS else COUNTS[-1]))
DEFAULT_COARSE = int(os.environ.get('DEFAULT_TOUCH', COUNTS[0]))
PFX = 'EFHJKMPQ'
CSS_SPLIT = int(float(os.environ.get('CSS_SPLIT', 14e6)))
tmp = tempfile.mkdtemp()


def build(k):
    n = COUNTS[k]
    nb = int(os.environ.get('NBOX_FIX', n // 2))
    env = dict(os.environ, NBOX=str(nb), NSPH=str(n - nb))
    if not PLAIN:
        env['PFX'] = PFX[k]
    out = os.path.join(tmp, f'e{n}.json')
    r = subprocess.run([sys.executable, os.path.join(HERE, os.environ.get('GEN', 'gen3d.py')), out], env=env, capture_output=True, text=True)
    if r.returncode:
        sys.exit(r.stderr)
    sys.stderr.write(r.stderr.strip().splitlines()[-1] + '\n')
    return json.load(open(out))


with ThreadPoolExecutor(max_workers=os.cpu_count() or 2) as ex:
    engines = list(ex.map(build, range(len(COUNTS))))
e0 = engines[0]
C = e0['consts']
VW, VH = C['VW'], C['VH']

css = []
for n, e in zip(COUNTS, engines):
    css.append(e['css'])
    css.append(f"#app:has(#n-{n}:checked) #{e['eng_id']}{{display:block}}")
# with no count picked yet: a bigger default for mouse machines, a small one for touch screens
eid = {n: e['eng_id'] for n, e in zip(COUNTS, engines)}
none = '#app:not(:has(.counts input:checked))'
css.append(f"{none} #{eid[DEFAULT_FINE]}{{display:block}}")
css.append(f"{none} label[for=n-{DEFAULT_FINE}]{{background:var(--acc);color:#14161a;border-color:var(--acc)}}")
if DEFAULT_COARSE != DEFAULT_FINE:
    css.append(f"@media (pointer:coarse){{{none} #{eid[DEFAULT_FINE]}{{display:none}}{none} #{eid[DEFAULT_COARSE]}{{display:block}}"
               f"{none} label[for=n-{DEFAULT_FINE}]{{background:var(--panel);color:var(--ink);border-color:var(--line)}}"
               f"{none} label[for=n-{DEFAULT_COARSE}]{{background:var(--acc);color:#14161a;border-color:var(--acc)}}}}")

# pointer grid: columns of cells, 10 view units each (mouse only)
CELL = 10
GC, GR = VW // CELL, VH // CELL
grid = []
UI = open(os.path.join(HERE, 'ui3d.css')).read()
html = open(os.path.join(HERE, 'page3d.html')).read()
f = lambda v: str(v)
rep = {
    '/*UI*/': UI.replace('/*GRID*/', '\n'.join(grid)).replace('/*BODIES*/', ''), '/*SHARED*/': e0['shared_css'],
    '/*ENGINES*/': '\n'.join(css),
    '<!--ENGINE_HTML-->': ''.join(e['html'] for e in engines),
    '<!--GRID-->': ('<b>' + '<i></i>' * GR + '</b>') * GC,
    '<!--COUNTS-->': ''.join(f'<input type="radio" name="n" id="n-{n}"><label for="n-{n}">{n}</label>' for n in COUNTS),
    '<!--SCENES-->': ''.join(
        f'<input type="radio" name="sc" id="sc-{sn}"{" checked" if si == 0 else ""}><label id="lb-{sn}" for="sc-{sn}">{sn}</label>'
        for si, sn in enumerate(e0['scenes'])),
    '__GC__': str(GC), '__GR__': str(GR),
    '__HVW__': f'{VW / 2:g}', '__HVH__': f'{VH / 2:g}', '__VW__': str(VW), '__VH__': str(VH), '__HS__': str(C['HS']),
    '__PERSP__': C['PERSP'], '__TILT__': C['TILT'], '__TY__': C['TY'], '__NDIST__': str(-float(C['DIST'])).rstrip('0').rstrip('.'),
    '__WX__': str(C['WX']), '__CEIL__': str(C['CEIL']), '__WZ__': str(C['WZ']), '__2WX__': str(2 * C['WX']), '__2WZ__': str(2 * C['WZ']),
    '__GRAV__': e0['grav'], '__NENG__': str(len(COUNTS)), '__COUNTS__': ', '.join(map(str, COUNTS)),
    '__NMAX__': str(max(COUNTS)), '__NREG__': str(max(e['nreg'] for e in engines)),
    '__NPROPS__': f"{max(e['nprops'] for e in engines):,}", '__NLEV__': str(max(e['nlev'] for e in engines)),
    '__ENGINES_SENTENCE__': (f"The page holds {len(COUNTS)} complete engines, one per body count ({', '.join(map(str, COUNTS))}); the ones not "
                             "selected are <code>display:none</code>, so the style engine never looks at them."),
}
for a, b in rep.items():
    html = html.replace(a, b)
if PLAIN and len(COUNTS) == 1:
    html = html.replace('</body>', '<!--BODYINFO ' + json.dumps(e0['bodyinfo']) + '-->\n</body>')
dst = sys.argv[1] if len(sys.argv) > 1 else 'rigid3d.html'
os.makedirs(os.path.dirname(os.path.abspath(dst)), exist_ok=True)
if MULTI:
    # one complete page per count; the count picker becomes links between the pages, so a page only
    # ever parses the one engine it shows (stem.html is a copy of the DEFAULT count's page)
    stem = dst[:-5] if dst.endswith('.html') else dst
    base = os.path.basename(stem)
    sizes = []
    for k, (n, e) in enumerate(zip(COUNTS, engines)):
        h = html
        # keep only this engine's markup and css
        for m, e2 in zip(COUNTS, engines):
            if m != n:
                h = h.replace(e2['html'], '').replace(e2['css'], '')
        links = ''.join(f'<a href="{base}-{m}.html"{" class=on" if m == n else ""}>{m}</a>' for m in COUNTS)
        cnt = ''.join(f'<input type="radio" name="n" id="n-{m}"><label for="n-{m}">{m}</label>' for m in COUNTS)
        h = h.replace(cnt, links)
        # this page's engine is always shown
        h = h.replace('</style>', f"#{e['eng_id']}{{display:block!important}}.counts a{{font:inherit;color:var(--ink);background:var(--panel);"
                      "border:1px solid var(--line);border-radius:4px;padding:4px 10px;text-decoration:none}.counts a.on{background:var(--acc);"
                      "color:#14161a;border-color:var(--acc)}.counts a:hover{border-color:var(--dim)}</style>", 1)
        h = h.replace('switching the count restarts the scene', 'each count is its own page')
        h = h.replace(f"The page holds {len(COUNTS)} complete engines, one per body count ({', '.join(map(str, COUNTS))}); the ones not "
                      "selected are <code>display:none</code>, so the style engine never looks at them.",
                      f"Each body count ({', '.join(map(str, COUNTS))}) is its own page with its own engine.")
        # a stylesheet over CSS_SPLIT goes out as linked .css files (hosts limit file size: Workers 25 MiB)
        # (split between top-level rules, in order)
        if len(e['css']) > CSS_SPLIT:
            parts, cur, size = [], [], 0
            for line in e['css'].split('\n'):
                if size > CSS_SPLIT * 0.9 and line.startswith('@'):
                    parts.append('\n'.join(cur)); cur, size = [], 0
                cur.append(line); size += len(line) + 1
            parts.append('\n'.join(cur))
            links = ''
            for k, part in enumerate(parts):
                cssname = f'{base}-{n}.{k + 1}.css'
                open(os.path.join(os.path.dirname(stem) or '.', cssname), 'w').write(part)
                links += f'<link rel="stylesheet" href="{cssname}">'
            h = h.replace(e['css'], '</style>' + links + '<style>', 1)
        out = f'{stem}-{n}.html'
        open(out, 'w').write(h)
        sizes.append(f'{n}: {len(h) / 1e6:.1f} MB')
        if n == DEFAULT_FINE:
            open(dst, 'w').write(h)
    print(f'{dst} + {stem}-N.html: ' + ', '.join(sizes), file=sys.stderr)
else:
    open(dst, 'w').write(html)
    print(f'{dst}: engines {COUNTS}, {len(html) / 1e6:.1f} MB', file=sys.stderr)
